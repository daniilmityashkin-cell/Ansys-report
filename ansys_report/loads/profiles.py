def _res(kind, name, A, Ix, Iy, D, B, tw, tf, source):
    """D - высота профиля, B - ширина полки, tw - стенка, tf - полка, мм; A - см², Ix/Iy - см⁴."""
    return {"kind": kind, "name": name, "area_cm2": round(float(A), 3), "Ix_cm4": round(float(Ix), 2), "Iy_cm4": round(float(Iy), 2),
            "D_mm": float(D), "B_mm": float(B), "TW_mm": float(tw), "TF_mm": float(tf), "source": source}


def _fmt(v):
    return ("%g" % v).replace(".", ",")


def i_from_dims(h, b, s, t):
    """Двутавр без галтелей: две полки b×t и стенка s×(h-2t), оси через центр. Возвращает A см², Ix, Iy см⁴."""
    hw = h - 2 * t
    A = 2 * b * t + hw * s
    Ix = (b * h ** 3 - (b - s) * hw ** 3) / 12.0
    Iy = (2 * t * b ** 3 + hw * s ** 3) / 12.0
    return A / 100.0, Ix / 1e4, Iy / 1e4


def channel_from_dims(h, b, s, t):
    """Швеллер без галтелей: полки b×t и стенка s×(h-2t). Iy - относительно центра тяжести по ширине."""
    hw = h - 2 * t
    A = 2 * b * t + hw * s
    Ix = (b * h ** 3 - (b - s) * hw ** 3) / 12.0
    xc = (2 * b * t * (b / 2.0) + hw * s * (s / 2.0)) / A
    Iy = 2 * (t * b ** 3 / 12.0 + b * t * (b / 2.0 - xc) ** 2) + hw * s ** 3 / 12.0 + hw * s * (s / 2.0 - xc) ** 2
    return A / 100.0, Ix / 1e4, Iy / 1e4


def angle_from_dims(b, t):
    """Равнополочный уголок без галтелей: Ix = Iy относительно центра тяжести (оси параллельны полкам)."""
    A = t * (2 * b - t)
    yc = (b * t * t / 2.0 + (b - t) * t * (t + (b - t) / 2.0)) / A
    Ix = b * t ** 3 / 12.0 + b * t * (yc - t / 2.0) ** 2 + t * (b - t) ** 3 / 12.0 + t * (b - t) * (t + (b - t) / 2.0 - yc) ** 2
    return A / 100.0, Ix / 1e4, Ix / 1e4


def _nums(text):
    return [float(x.replace(",", ".")) for x in re.findall(r"\d+(?:[.,]\d+)?", text)]


def catalog_names() -> list[str]:
    """Подписи для подсказок в студии (в том виде, как их понимает parse_profile)."""
    out = [f"Двутавр {k}" for k in I_BEAMS] + [f"Швеллер {k}П" for k in CHANNELS]
    out += [f"Уголок L{b}×{b}×{t}" for (b, t) in ANGLES]
    return out + ["Двутавр 250×125×6×9", "Швеллер 240×90×5,6×10", "Уголок 90×90×6", "Труба 108×4", "Труба 100×50×4", "Полоса 200×10", "Свои A=34,8 Ix=3460 Iy=198"]


HINT = ("Выберите профиль из списка (например «Двутавр 24», «Швеллер 24П», «Уголок L90×90×6») или задайте его габаритами "
        "(«Двутавр 250×125×6×9», «Труба 108×4», «Полоса 200×10») или значениями («Свои A=34,8 Ix=3460 Iy=198», см² и см⁴).")


def parse_profile(label: str) -> dict:
    """Подпись сечения → свойства. ValueError с понятным текстом, если подпись не распознана или профиля нет в каталоге."""
    raw = (label or "").strip()
    if not raw:
        raise ValueError("Сечение не задано. " + HINT)
    t = raw.lower().replace("×", "x").replace("х", "x").replace("*", "x").replace("∟", "l").replace("ø", "").replace("⌀", "")
    t = re.sub(r"\s+", " ", t)
    if t.startswith(("свои", "свой", "своё", "a=", "а=")):
        vals = {}
        for key, val in re.findall(r"(a|а|ix|iy|iх)\s*=\s*(\d+(?:[.,]\d+)?)", t):
            vals[{"а": "a", "iх": "ix"}.get(key, key)] = float(val.replace(",", "."))
        if not {"a", "ix", "iy"} <= set(vals) or min(vals.values()) <= 0:
            raise ValueError("Свои характеристики: укажите A (см²), Ix и Iy (см⁴), например «Свои A=34,8 Ix=3460 Iy=198».")
        A = vals["a"]
        side = math.sqrt(A * 100.0)                                   # габариты для крутильной жёсткости неизвестны: эквивалентный тонкий профиль
        return _res("custom", f"A={_fmt(A)} Ix={_fmt(vals['ix'])} Iy={_fmt(vals['iy'])}", A, vals["ix"], vals["iy"], side, side, side / 10, side / 10, "введено")
    m = re.match(r"(двутавр|дв|i|швеллер|шв|\[|уголок|ул|l|труба|тр|полоса|лист|пластина)\s*(.*)$", t)
    if not m:
        raise ValueError(f"«{raw}»: не удалось определить тип профиля. " + HINT)
    kind, rest = m.group(1), m.group(2).strip()
    if kind in ("двутавр", "дв", "i"):
        n = _nums(rest)
        if len(n) == 4 and "x" in rest:
            h, b, s, tf = n
            if min(n) <= 0 or h <= 2 * tf or b <= s:
                raise ValueError(f"«{raw}»: размеры двутавра заданы неверно (H×B×s×t, мм).")
            return _res("i", f"Двутавр {_fmt(h)}×{_fmt(b)}×{_fmt(s)}×{_fmt(tf)}", *i_from_dims(h, b, s, tf), h, b, s, tf, "по габаритам (A, Ix −1…2 %, Iy до +25 %)")
        mm = re.match(r"(\d+(?:[.,]\d+)?)\s*(.*)$", rest)
        key = mm.group(1).replace(",", ".") if mm else ""
        if mm and key in I_BEAMS and not mm.group(2).strip():
            h, b, s, tf, A, Ix, Iy = I_BEAMS[key]
            return _res("i", f"Двутавр {key}", A, Ix, Iy, h, b, s, tf, "ГОСТ 8239-89")
        raise ValueError(f"«{raw}»: двутавра с таким номером нет в каталоге (ГОСТ 8239: 10…60). Для двутавров серий Б, Ш, К задайте габариты: «Двутавр 250×125×6×9» (H×B×s×t, мм).")
    if kind in ("швеллер", "шв", "["):
        n = _nums(rest)
        if len(n) == 4 and "x" in rest:
            h, b, s, tf = n
            if min(n) <= 0 or h <= 2 * tf or b <= s:
                raise ValueError(f"«{raw}»: размеры швеллера заданы неверно (H×B×s×t, мм).")
            return _res("channel", f"Швеллер {_fmt(h)}×{_fmt(b)}×{_fmt(s)}×{_fmt(tf)}", *channel_from_dims(h, b, s, tf), h, b, s, tf, "по габаритам (A, Ix −1…2 %, Iy до +25 %)")
        mm = re.match(r"(\d+(?:[.,]\d+)?)\s*([пуpyэ]?)\s*$", rest)
        if mm:
            key = mm.group(1).replace(",", ".")
            if key in CHANNELS:
                h, b, s, tf, A, Ix, Iy = CHANNELS[key]
                return _res("channel", f"Швеллер {key}{ {'у': 'У', 'y': 'У'}.get(mm.group(2), 'П')}", A, Ix, Iy, h, b, s, tf, "ГОСТ 8240-97")
        raise ValueError(f"«{raw}»: швеллера с таким номером нет в каталоге (ГОСТ 8240: 5…40). Можно задать габаритами: «Швеллер 240×90×5,6×10».")
    if kind in ("уголок", "ул", "l"):
        n = _nums(rest)
        if len(n) == 3:
            b, b2, tt = n
            if abs(b - b2) > 1e-9:
                raise ValueError(f"«{raw}»: неравнополочные уголки не поддерживаются, задайте «Свои A=… Ix=… Iy=…».")
        elif len(n) == 2:
            b, tt = n
        else:
            raise ValueError(f"«{raw}»: для уголка укажите полку и толщину, например «Уголок L90×90×6».")
        if b <= 0 or tt <= 0 or tt >= b:
            raise ValueError(f"«{raw}»: размеры уголка заданы неверно.")
        key = (int(b) if b == int(b) else b, int(tt) if tt == int(tt) else tt)
        if key in ANGLES:
            A, I = ANGLES[key]
            return _res("angle", f"Уголок L{_fmt(b)}×{_fmt(b)}×{_fmt(tt)}", A, I, I, b, b, tt, tt, "ГОСТ 8509-93")
        return _res("angle", f"Уголок L{_fmt(b)}×{_fmt(b)}×{_fmt(tt)}", *angle_from_dims(b, tt), b, b, tt, tt, "по габаритам (A, Ix −1…2 %, Iy до +25 %)")
    if kind in ("труба", "тр"):
        n = _nums(rest)
        if len(n) == 2:                                               # круглая D×t
            d, tt = n
            if d <= 0 or tt <= 0 or 2 * tt >= d:
                raise ValueError(f"«{raw}»: размеры трубы заданы неверно (D×t, мм).")
            I = math.pi * (d ** 4 - (d - 2 * tt) ** 4) / 64.0
            A = math.pi * (d ** 2 - (d - 2 * tt) ** 2) / 4.0
            return _res("pipe", f"Труба {_fmt(d)}×{_fmt(tt)}", A / 100.0, I / 1e4, I / 1e4, d, d, tt, tt, "по габаритам")
        if len(n) == 3:                                               # прямоугольная H×B×t
            h, b, tt = n
            if min(n) <= 0 or 2 * tt >= min(h, b):
                raise ValueError(f"«{raw}»: размеры профильной трубы заданы неверно (H×B×t, мм).")
            A = h * b - (h - 2 * tt) * (b - 2 * tt)
            Ix = (b * h ** 3 - (b - 2 * tt) * (h - 2 * tt) ** 3) / 12.0
            Iy = (h * b ** 3 - (h - 2 * tt) * (b - 2 * tt) ** 3) / 12.0
            return _res("pipe", f"Труба {_fmt(h)}×{_fmt(b)}×{_fmt(tt)}", A / 100.0, Ix / 1e4, Iy / 1e4, h, b, tt, tt, "по габаритам")
        raise ValueError(f"«{raw}»: труба — «Труба 108×4» (D×t) или «Труба 100×50×4» (H×B×t), мм.")
    n = _nums(rest)                                                   # полоса / лист: ширина × толщина, мм
    if len(n) != 2 or min(n) <= 0:
        raise ValueError(f"«{raw}»: полоса — «Полоса 200×10» (ширина × толщина, мм).")
    w, tt = n
    A, Ix, Iy = w * tt, tt * w ** 3 / 12.0, w * tt ** 3 / 12.0        # Ix - в плоскости большей стороны
    return _res("strip", f"Полоса {_fmt(w)}×{_fmt(tt)}", A / 100.0, Ix / 1e4, Iy / 1e4, w, tt, tt, tt, "по габаритам")


def section_props(label: str) -> dict:
    """Свойства сечения в формате файла проекта «РВС Геометрия» (то, что читает beams._sec): computed + dimensions_m."""
    p = parse_profile(label)
    return {"name": p["name"], "computed": {"area_cm2": p["area_cm2"], "Ix_cm4": p["Ix_cm4"], "Iy_cm4": p["Iy_cm4"]},
            "dimensions_m": {"D": p["D_mm"] / 1000.0, "Base": p["B_mm"] / 1000.0, "TW": p["TW_mm"] / 1000.0, "TF": p["TF_mm"] / 1000.0}, "label": label.strip()}
