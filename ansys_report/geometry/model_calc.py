"""Точка подключения расчётного модуля: замеры → вмятины и нагрузки.

Сейчас вмятины берутся из проекта замеров (файл JSON), нагрузки не считаются. Когда скрипт научного руководителя
будет готов, его логика подключается внутри `run`: функция получает проект замеров и параметры объекта
(плотность продукта, уровень налива, снеговая и ветровая нагрузки, избыточное давление) и возвращает словарь с ключами
`loads` и `dents`. Скрипт работает только на сервере и заказчику не передаётся.
"""
from __future__ import annotations

from . import check


def run(project: dict, params: dict | None = None) -> dict:
    res = check.analyze(project)
    return {"analysis": res, "dents": res["dents"], "loads": None, "params": params or {}}
