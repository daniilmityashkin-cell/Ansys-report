def thickness_groups(th):
    """[16,14,13,12,12,12,11] -> 'первого пояса – 16,0 мм; ... с четвертого по шестой – 12,0 мм ...'"""
    names = ["первого", "второго", "третьего", "четвертого", "пятого", "шестого", "седьмого", "восьмого",
             "девятого", "десятого", "одиннадцатого", "двенадцатого", "тринадцатого", "четырнадцатого", "пятнадцатого"]
    nom = ["первый", "второй", "третий", "четвертый", "пятый", "шестой", "седьмой", "восьмой",
           "девятый", "десятый", "одиннадцатый", "двенадцатый", "тринадцатый", "четырнадцатый", "пятнадцатый"]
    parts, i = [], 0
    while i < len(th):
        j = i
        while j + 1 < len(th) and th[j + 1] == th[i]:
            j += 1
        v = f"{th[i]:.1f}".replace(".", ",")
        parts.append(f"{names[i]} – {v} мм" if i == j else f"с {names[i]} по {nom[j]} – {v} мм")
        i = j + 1
    return "; ".join(parts)
